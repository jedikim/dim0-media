/**
 * Returns the categories with their icon lists filtered by `query`. An
 * icon matches when the query is a substring of its name or a prefix of
 * any tokenized word (so "pin" matches "MapPin"). An empty/whitespace
 * query returns the input untouched.
 */
export const filterPickerCategories = (
  categories: ReadonlyArray<PickerCategory>,
  query: string,
): ReadonlyArray<PickerCategory> => {
  const trimmed = query.trim().toLowerCase()

  if (!trimmed) return categories

  return categories.map((category) => ({
    ...category,
    icons: category.icons.filter((icon) => {
      const lowered = icon.name.toLowerCase()

      if (lowered.includes(trimmed)) return true

      return tokenizeIconName(icon.name).some((token) => token.startsWith(trimmed))
    }),
  }))
}
