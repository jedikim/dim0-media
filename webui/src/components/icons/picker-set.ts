/**
 * Flat name -> component map for render-path lookups (e.g. rendering an
 * icon that was previously persisted by name).
 */
export const PICKER_ICON_MAP: ReadonlyMap<string, Icon> = new Map(
  PICKER_CATEGORIES.flatMap((category) =>
    category.icons.map(({ name, component }) => [name, component] as const),
  ),
)


/**
 * Splits a PascalCase icon name into lowercase words for search matching.
 * e.g. "MapPin" -> ["map", "pin"]
 */
export const tokenizeIconName = (name: string): string[] =>
  name
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)


